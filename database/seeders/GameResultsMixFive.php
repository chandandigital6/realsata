                            'status' => 'declared',
                            'created_at' => $timestamp,
                            'updated_at' => $timestamp,
                        ];
                    }
                }

                foreach (array_chunk($insertRows, 500) as $chunk) {
                    GameResult::insert($chunk);
                }
            }
