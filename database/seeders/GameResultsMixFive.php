                        $month = $index + 1;

                        if (in_array($result, ['-', '--'], true)) {
                            continue;
                        }

                        if (!preg_match('/^\d{1,2}$/', $result)) {
                            throw new RuntimeException("Invalid result for {$slug}: {$result}");
                        }

                        if (!checkdate($month, $day, $year)) {
                            continue;
                        }

                        $insertRows[] = [
                            'game_id' => $game->id,
                            'result_date' => sprintf('%04d-%02d-%02d', $year, $month, $day),
